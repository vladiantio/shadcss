import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../..");
const registry = JSON.parse(
  readFileSync(join(packageRoot, "registry", "registry.json"), "utf8")
);

const items = registry.items.filter((item) => item.status === "stable");
const baseFiles = items
  .flatMap((item) => item.files)
  .filter((file) => file.role === "base");
const themeFiles = items
  .flatMap((item) => item.files)
  .filter((file) => file.role === "theme");

const lines = [
  "/* Generated by packages/shadcss/scripts/generate-docs-css.mjs. Do not edit. */",
  "@layer shadcss.tokens, shadcss.reset, shadcss.base, shadcss.components, shadcss.theme, shadcss.utilities, docs;",
  "",
  ...baseFiles.map((file) => `@import "../../../packages/shadcss/registry/${file.path}";`),
  "",
  ...themeFiles.map((file) => `@import "../../../packages/shadcss/registry/${file.path}";`),
  ""
];

writeFileSync(join(repoRoot, "web", "src", "styles", "shadcss.css"), lines.join("\n"));
console.log(
  `Generated web/src/styles/shadcss.css (${baseFiles.length + themeFiles.length} imports).`
);
