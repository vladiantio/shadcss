import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../..");
const registryDir = join(packageRoot, "registry");
const registry = JSON.parse(readFileSync(join(registryDir, "registry.json"), "utf8"));

const LAYER_ORDER =
  "loseta.tokens, loseta.reset, loseta.base, loseta.components, loseta.style, loseta.utilities, docs";

const items = registry.items.filter((item) => item.status === "stable");
const files = items.flatMap((item) => item.files);
const baseFiles = files.filter((file) => file.role === "base");

const lines = [
  "/* Generated by packages/loseta/scripts/generate-docs-css.mjs. Do not edit. */",
  `@layer ${LAYER_ORDER};`,
  "",
  ...baseFiles.map((file) => `@import "../../../packages/loseta/registry/${file.path}";`),
  ""
];

writeFileSync(join(repoRoot, "web", "src", "styles", "loseta.css"), lines.join("\n"));

const publicStyles = join(repoRoot, "web", "public", "styles");
rmSync(publicStyles, { recursive: true, force: true });
mkdirSync(publicStyles, { recursive: true });

for (const style of registry.styles) {
  const styleFiles = files.filter(
    (file) => file.role === "style" && file.path.startsWith(`styles/${style.name}/`)
  );
  const styleLines = [
    "/* Generated by packages/loseta/scripts/generate-docs-css.mjs. Do not edit. */",
    `/* Style: ${style.title} (${style.name}) */`,
    `@layer ${LAYER_ORDER};`,
    "",
    ...styleFiles.map((file) =>
      readFileSync(join(registryDir, file.path), "utf8").trim()
    ),
    ""
  ];
  writeFileSync(join(publicStyles, `${style.name}.css`), styleLines.join("\n"));
}

console.log(
  `Generated web/src/styles/loseta.css (${baseFiles.length} imports) and web/public/styles (${registry.styles.length} styles).`
);
