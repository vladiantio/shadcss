import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../..");
const registry = JSON.parse(
  readFileSync(join(packageRoot, "registry", "registry.json"), "utf8")
);

const items = registry.items.filter((item) => item.status === "stable");
const baseFiles = items
  .flatMap((item) => item.files)
  .filter((file) => file.role === "base");
const styleFiles = items
  .flatMap((item) => item.files)
  .filter((file) => file.role === "style");

const lines = [
  "/* Generated by packages/loseta/scripts/generate-docs-css.mjs. Do not edit. */",
  "@layer loseta.tokens, loseta.reset, loseta.base, loseta.components, loseta.style, loseta.utilities, docs;",
  "",
  ...baseFiles.map((file) => `@import "../../../packages/loseta/registry/${file.path}";`),
  "",
  ...styleFiles.map((file) => `@import "../../../packages/loseta/registry/${file.path}";`),
  ""
];

writeFileSync(join(repoRoot, "web", "src", "styles", "loseta.css"), lines.join("\n"));
console.log(
  `Generated web/src/styles/loseta.css (${baseFiles.length + styleFiles.length} imports).`
);
