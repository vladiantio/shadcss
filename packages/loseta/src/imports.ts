import { dirname, relative } from "node:path";
import { fromProjectRoot, indexCssPath } from "./config.js";
import { readTextIfExists, writeText } from "./fs.js";
import type { Registry, LosetaConfig } from "./types.js";

const LAYER_ORDER =
  "loseta.tokens, loseta.reset, loseta.base, loseta.components, loseta.style, loseta.utilities";

function toPosix(path: string): string {
  return path.split("\\").join("/");
}

function importLine(target: string): string {
  return `@import "./${toPosix(target)}";`;
}

/** Generates the managed index.css for the installed item set and style. */
export function generateIndex(
  registry: Registry,
  installed: Set<string>,
  style: string
): string {
  const selected = registry.items.filter((item) => installed.has(item.name));
  const stylePrefix = `styles/${style}/`;
  const baseFiles = selected
    .flatMap((item) => item.files)
    .filter((file) => file.role === "base")
    .map((file) => importLine(file.target));
  const styleFiles = selected
    .flatMap((item) => item.files)
    .filter((file) => file.role === "style" && file.path.startsWith(stylePrefix))
    .map((file) => importLine(file.target));

  return [
    "/* Generated by loseta. Do not edit this file directly. */",
    `@layer ${LAYER_ORDER};`,
    "",
    ...baseFiles,
    "",
    ...styleFiles,
    ""
  ].join("\n");
}

/** Writes the generated index.css. */
export function writeIndex(
  projectRoot: string,
  config: LosetaConfig,
  registry: Registry,
  installed: Set<string>
): void {
  writeText(indexCssPath(projectRoot, config), generateIndex(registry, installed, config.style));
}

/**
 * Adds a single @import for loseta/index.css to the user's CSS entrypoint.
 * Returns true when the entrypoint was modified.
 */
export function addEntrypointImport(projectRoot: string, config: LosetaConfig): boolean {
  if (!config.entrypoint) return false;

  const entrypoint = fromProjectRoot(projectRoot, config.entrypoint);
  const index = indexCssPath(projectRoot, config);
  const existing = readTextIfExists(entrypoint);
  if (existing === undefined) return false;

  const importPath = toPosix(relative(dirname(entrypoint), index));
  const line = `@import "${importPath.startsWith(".") ? importPath : `./${importPath}`}";`;
  if (existing.includes(line)) return false;

  const lines = existing.split(/\r?\n/);
  let insertAt = 0;
  while (insertAt < lines.length && /^\s*@charset\b/.test(lines[insertAt] ?? "")) {
    insertAt += 1;
  }
  lines.splice(insertAt, 0, line);
  writeText(entrypoint, lines.join("\n"));
  return true;
}
